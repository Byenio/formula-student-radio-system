  #define STATS_HAS_RTOS    0
  extern uint32_t stats_host_ms;
  extern uint32_t stats_host_core_hz;
  #define STATS_NOW_MS()    (stats_host_ms)
  #define STATS_CORE_HZ()   (stats_host_core_hz)
#else
  #include "main.h"
  #define STATS_NOW_MS()    HAL_GetTick()
  #define STATS_CORE_HZ()   SystemCoreClock
  #if defined(STM32G491xx)
    #define STATS_BOARD_ID  0U
    #define STATS_HAS_RTOS  1
  #elif defined(STM32U375xx)
    #define STATS_BOARD_ID  1U
    #define STATS_HAS_RTOS  0
  #else
    #error "stats.c: unknown board -- add it to the board configuration block"
  #endif
#endif

